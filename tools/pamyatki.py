def _rules(items, yes=True):
    out = ['<div class="rules">']
    for t, d in items:
        out.append('<div class="rule rule--%s">%s'
                   '<span class="rule__t"><span class="t-body-md">%s</span>'
                   '<span class="t-body-sm rule__d">%s</span></span></div>'
                   % ('yes' if yes else 'no',
                      ic('check' if yes else 'close', 20), t, d))
    out.append('</div>')
    return '\n'.join(out)


def _timeline(items):
    out = ['<div class="steps">']
    for day, t, d in items:
        out.append('<div class="step">'
                   '<span class="step__num step__num--day">%s</span>'
                   '<div class="step__tx"><span class="t-card-title">%s</span>'
                   '<p class="t-body step__d">%s</p></div></div>' % (day, t, d))
    out.append('</div>')
    return '\n'.join(out)


